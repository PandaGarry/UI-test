// Probe: which pointer events reach the document for a MOUSE tap vs a TOUCH tap on the map.
import chromium from "@sparticuz/chromium";
import puppeteer from "puppeteer-core";
const sleep = ms => new Promise(r => setTimeout(r, ms));
const b = await puppeteer.launch({executablePath: await chromium.executablePath(), args: chromium.args, headless: true, defaultViewport: {width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true}});
const p = await b.newPage();
await p.goto("http://localhost:8081/", {waitUntil: "networkidle0", timeout: 60000}); await sleep(1500);
const tapEl = async sel => { const box = await p.evaluate(s => { const e = document.querySelector(s); if (!e) return null; const r = e.getBoundingClientRect(); return {x: r.x + r.width / 2, y: r.y + r.height / 2}; }, sel); if (box) await p.mouse.click(box.x, box.y); };
await p.click("#playerNameInput", {clickCount: 3}); await p.type("#playerNameInput", "Tester"); await sleep(300);
await tapEl("#btnStartSingleplayer"); await sleep(1200);
await p.click("#lobbyBotsNumber", {clickCount: 3}); await p.type("#lobbyBotsNumber", "50");
await p.evaluate(() => { const i = document.getElementById("lobbyBotsNumber"); i.dispatchEvent(new Event("input", {bubbles: true})); i.blur(); });
await sleep(400); await tapEl("#lobbyStart");
const t0 = Date.now(); while (Date.now() - t0 < 60000 && !(await p.evaluate(() => { const e = document.querySelector("#spawnPhaseTimer"); return !!e && e.style.display !== "none"; }))) await sleep(100);
await p.mouse.click(200, 380); await sleep(300);
const w0 = Date.now(); while (Date.now() - w0 < 30000 && await p.evaluate(() => { const e = document.querySelector("#spawnPhaseTimer"); return !!e && e.style.display !== "none"; })) await sleep(200);
await sleep(800);
await p.evaluate(() => { window.__ev = []; for (const t of ["pointerdown", "pointerup", "click"]) document.addEventListener(t, e => window.__ev.push({t, type: e.pointerType || "", tgt: (e.target.id || e.target.className || e.target.tagName || "").toString().slice(0, 40), x: Math.round(e.clientX), y: Math.round(e.clientY), cap: e.isTrusted}), true); });
const menu = () => p.evaluate(() => { const r = document.querySelector("#radialRoot"); return !!r && !r.hidden; });
await p.mouse.click(200, 400); await sleep(250);
const mouseRes = {open: await menu(), ev: await p.evaluate(() => window.__ev.splice(0))};
await p.mouse.click(5, 5); await sleep(200);
await p.touchscreen.tap(200, 400); await sleep(250); console.log("ALOG " + JSON.stringify(await p.evaluate(() => (window.__aLog || []).slice(-3))));
const touchRes = {open: await menu(), ev: await p.evaluate(() => window.__ev.splice(0))};
console.log("IM " + JSON.stringify(await p.evaluate(() => window.__imLog || [])));
console.log("MOUSE " + JSON.stringify(mouseRes));
console.log("TOUCH " + JSON.stringify(touchRes));
await b.close();
